def _validate_data():
    standard_ids = {info.identifier for info in STANDARD_INFOS}
    seen = set()
    for spec in SHAPE_KEY_SPECS:
        if spec.standard not in standard_ids:
            raise RuntimeError(f"未知形态键标准：{spec.standard}")
        identity = (spec.standard, spec.name)
        if identity in seen:
            raise RuntimeError(
                f"标准 {spec.standard} 中存在重复形态键：{spec.name}")
        seen.add(identity)


_validate_data()



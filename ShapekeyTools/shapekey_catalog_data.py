_STANDARD_BY_ID = {
    info.identifier: info
    for info in STANDARD_INFOS
}


def _key(
        standard, name, *, role='TEMPLATE', region='OTHER',
        side='NONE', semantic='OTHER', canonical=None, context=None,
        tags=(), note=''):
    """只补标准级公共字段，不根据名称推断任何事实。"""
    info = _STANDARD_BY_ID[standard]
    return ShapeKeySpec(
        standard=standard,
        family=info.family,
        name=name,
        role=role,
        region=region,
        side=side,
        semantic=semantic,
        canonical=canonical,
        context=context,
        side_reliable=info.side_reliable,
        tags=info.categories | frozenset(tags),
        source_urls=info.source_urls,
        note=note,
    )



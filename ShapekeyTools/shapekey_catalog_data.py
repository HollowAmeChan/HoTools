"""跨工具共用的逐键形态键事实。"""

from dataclasses import dataclass


@dataclass(frozen=True)
class ShapeKeyStandardInfo:
    """一个标准的 UI 信息和默认属性。"""

    identifier: str
    family: str
    label: str
    description: str
    categories: frozenset = frozenset()
    source_urls: tuple = ()
    side_reliable: bool = False


@dataclass(frozen=True)
class ShapeKeySpec:
    """某个标准中的一个原始形态键记录。"""

    standard: str
    family: str
    name: str
    role: str = 'TEMPLATE'
    region: str = 'OTHER'
    side: str = 'NONE'
    semantic: str = 'OTHER'
    canonical: str | None = None
    context: str | None = None
    side_reliable: bool = False
    tags: frozenset = frozenset()
    source_urls: tuple = ()
    note: str = ''

    @property
    def is_template(self):
        return self.role == 'TEMPLATE'

